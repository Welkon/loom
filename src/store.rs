//! Project manifest, lock file, hashes, and atomic writes for loom.

use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::fs;
use std::path::{Component, Path, PathBuf};

#[derive(Clone, Default)]
pub(super) struct LockEntry {
    pub id: String,
    pub version: String,
    pub sha256: String,
    pub path: String,
    pub source: String,
    pub commit: String,
}

pub(super) fn read_manifest(path: &Path) -> Result<BTreeMap<String, String>, (String, u8)> {
    let mut units = BTreeMap::new();
    if !path.exists() {
        return Ok(units);
    }
    let text = fs::read_to_string(path).map_err(io_error)?;
    let mut in_units = false;
    for line in text.lines() {
        let line = line.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        if line.starts_with('[') {
            in_units = line == "[units]";
            continue;
        }
        if !in_units {
            continue;
        }
        if let Some((key, value)) = line.split_once('=') {
            units.insert(key.trim().to_string(), unquote(value));
        }
    }
    Ok(units)
}

pub(super) fn write_manifest(
    path: &Path,
    units: &BTreeMap<String, String>,
) -> Result<(), (String, u8)> {
    let mut text = String::from("[units]\n");
    for (id, version) in units {
        text.push_str(&format!("{id} = {}\n", quote(version)));
    }
    atomic_write(path, &text)
}

pub(super) fn read_lock(path: &Path) -> Result<Vec<LockEntry>, (String, u8)> {
    let mut entries = Vec::new();
    if !path.exists() {
        return Ok(entries);
    }
    let text = fs::read_to_string(path).map_err(io_error)?;
    let mut current: Option<LockEntry> = None;
    for line in text.lines() {
        let line = line.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        if line == "[[unit]]" {
            if let Some(entry) = current.take() {
                entries.push(entry);
            }
            current = Some(LockEntry::default());
            continue;
        }
        let Some(entry) = current.as_mut() else {
            continue;
        };
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        let value = unquote(value);
        match key.trim() {
            "id" => entry.id = value,
            "version" => entry.version = value,
            "sha256" => entry.sha256 = value,
            "path" => entry.path = value,
            "source" => entry.source = value,
            "commit" => entry.commit = value,
            _ => {}
        }
    }
    if let Some(entry) = current.take() {
        entries.push(entry);
    }
    Ok(entries)
}

pub(super) fn write_lock(path: &Path, entries: &[LockEntry]) -> Result<(), (String, u8)> {
    let mut text = String::from("version = 1\n");
    for entry in entries {
        text.push_str("\n[[unit]]\n");
        text.push_str(&format!("id = {}\n", quote(&entry.id)));
        text.push_str(&format!("version = {}\n", quote(&entry.version)));
        text.push_str(&format!("sha256 = {}\n", quote(&entry.sha256)));
        text.push_str(&format!("path = {}\n", quote(&entry.path)));
        text.push_str(&format!("source = {}\n", quote(&entry.source)));
        text.push_str(&format!("commit = {}\n", quote(&entry.commit)));
    }
    atomic_write(path, &text)
}

pub(super) fn hash_installed(root: &Path, paths: &[String]) -> Option<String> {
    let mut hasher = Sha256::new();
    for relative in paths {
        let content = fs::read(root.join(relative)).ok()?;
        hasher.update(relative.as_bytes());
        hasher.update(b"\0");
        hasher.update(&content);
        hasher.update(b"\0");
    }
    Some(format!("{:x}", hasher.finalize()))
}

pub(super) fn provenance(
    id: &str,
    version: &str,
    source: &str,
    commit: &str,
    sha256: &str,
) -> String {
    format!(
        "# Provenance\n\n- unit: {id}\n- version: {version}\n- source: {source}\n- commit: {commit}\n- sha256: {sha256}\n- license: MIT\n\nGenerated by `emb-agent loom add`.\n"
    )
}

pub(super) fn safe_join(root: &Path, value: &str) -> Result<PathBuf, (String, u8)> {
    let path = Path::new(value);
    if path.is_absolute()
        || value.is_empty()
        || path
            .components()
            .any(|component| !matches!(component, Component::Normal(_)))
    {
        return Err(("invalid_loom_destination".to_string(), 2));
    }
    Ok(root.join(path))
}

pub(super) fn atomic_write(path: &Path, content: &str) -> Result<(), (String, u8)> {
    let parent = path
        .parent()
        .ok_or_else(|| ("invalid_loom_path".to_string(), 1))?;
    fs::create_dir_all(parent).map_err(io_error)?;
    let name = path
        .file_name()
        .map(|value| value.to_string_lossy().into_owned())
        .unwrap_or_else(|| "loom".to_string());
    let temporary = parent.join(format!(".{name}.tmp-{}", std::process::id()));
    fs::write(&temporary, content).map_err(io_error)?;
    if cfg!(windows) && path.exists() {
        let _ = fs::remove_file(path);
    }
    fs::rename(&temporary, path).map_err(io_error)
}

pub(super) fn quote(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

pub(super) fn unquote(value: &str) -> String {
    let value = value.trim();
    value
        .strip_prefix('"')
        .and_then(|value| value.strip_suffix('"'))
        .unwrap_or(value)
        .to_string()
}

pub(super) fn io_error(error: std::io::Error) -> (String, u8) {
    (format!("loom_io_failed:{error}"), 1)
}
